-- Pushup challenge database, with teams. Run this whole file in the Supabase SQL
-- editor. It is safe to run again, and it upgrades the first (team-less) version.
--
-- The app never touches the tables directly: it calls the functions below, and
-- every function needs a team code. So a team's entries can only be read or
-- changed by someone who knows its code, and nobody can list all teams.

create table if not exists public.teams (
  code       text primary key,                  -- 6 characters, e.g. K7P2QX
  name       text not null check (char_length(name) between 1 and 30),
  created_at timestamptz not null default now()
);

create table if not exists public.entries (
  id         uuid primary key,                  -- generated by the app, so retries never duplicate
  user_name  text not null check (char_length(user_name) between 1 and 20),
  day        date not null,
  count      int  not null check (count between 1 and 100),
  created_at timestamptz not null default now()
);

alter table public.entries add column if not exists team_code text references public.teams (code) on delete cascade;

-- Each team's challenge rules (the settings page edits them; everyone in the team shares them).
alter table public.teams add column if not exists goal int not null default 30;
alter table public.teams add column if not exists allowed_misses int not null default 2;
alter table public.teams add column if not exists end_date date not null default '2026-12-24';
do $$ begin
  alter table public.teams add constraint teams_goal_range check (goal between 1 and 100);
exception when duplicate_object then null; end $$;
do $$ begin
  alter table public.teams add constraint teams_misses_range check (allowed_misses between 0 and 30);
exception when duplicate_object then null; end $$;
create index if not exists entries_team_idx on public.entries (team_code, day);

-- Rows from before teams existed belong to no team; the app re-uploads them when you join one.
delete from public.entries where team_code is null;

-- Who is in each team (also people who haven't logged anything yet). Names are unique per team.
create table if not exists public.team_members (
  team_code text not null references public.teams (code) on delete cascade,
  user_name text not null check (char_length(user_name) between 1 and 20),
  joined_at timestamptz not null default now()
);
create unique index if not exists team_members_name_idx on public.team_members (team_code, lower(user_name));

-- Everyone who already has entries in a team is a member.
insert into public.team_members (team_code, user_name)
select distinct on (e.team_code, lower(e.user_name)) e.team_code, e.user_name
from public.entries e
where e.team_code is not null
on conflict do nothing;

-- Phones that asked for notifications about their team (Web Push subscriptions).
create table if not exists public.push_subscriptions (
  endpoint   text primary key,
  team_code  text not null references public.teams (code) on delete cascade,
  user_name  text not null,
  p256dh     text not null,
  auth       text not null,
  created_at timestamptz not null default now()
);

-- Notifications are written in each phone's language.
alter table public.push_subscriptions add column if not exists lang text not null default 'en';

-- No direct table access for the app's public key: only the functions below.
alter table public.teams enable row level security;
alter table public.entries enable row level security;
alter table public.team_members enable row level security;
alter table public.push_subscriptions enable row level security;
drop policy if exists "Everyone can read" on public.entries;
drop policy if exists "Everyone can add" on public.entries;
drop policy if exists "Undo recent entries" on public.entries;
revoke all on table public.teams, public.entries, public.team_members, public.push_subscriptions from anon, authenticated;

-- Creates a team with a fresh code. Returns {"code": ..., "name": ...}.
create or replace function public.create_team(p_name text)
returns json
language plpgsql security definer set search_path = public as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; -- no 0/O or 1/I look-alikes
  new_code text;
begin
  if char_length(trim(coalesce(p_name, ''))) not between 1 and 30 then
    raise exception 'Team name must be 1 to 30 characters';
  end if;
  loop
    new_code := '';
    for i in 1..6 loop
      new_code := new_code || substr(alphabet, 1 + floor(random() * length(alphabet))::int, 1);
    end loop;
    begin
      insert into teams (code, name) values (new_code, trim(p_name));
      exit;
    exception when unique_violation then
      null; -- code already taken: draw another one
    end;
  end loop;
  return (select json_build_object('code', t.code, 'name', t.name, 'goal', t.goal,
                                    'allowed_misses', t.allowed_misses, 'end_date', t.end_date)
          from teams t where t.code = new_code);
end $$;

-- Looks a team up by code. Returns its name and rules, or null when there is no such team.
create or replace function public.find_team(p_code text)
returns json
language sql stable security definer set search_path = public as $$
  select json_build_object('code', t.code, 'name', t.name, 'goal', t.goal,
                           'allowed_misses', t.allowed_misses, 'end_date', t.end_date)
  from teams t where t.code = upper(trim(p_code));
$$;

-- Changes a team's rules (anyone in the team can). Returns the team like find_team.
create or replace function public.update_team_rules(p_code text, p_goal int, p_allowed_misses int, p_end_date date)
returns json
language plpgsql security definer set search_path = public as $$
declare result json;
begin
  update teams set goal = p_goal, allowed_misses = p_allowed_misses, end_date = p_end_date
  where code = upper(trim(p_code))
  returning json_build_object('code', teams.code, 'name', teams.name, 'goal', teams.goal,
                              'allowed_misses', teams.allowed_misses, 'end_date', teams.end_date) into result;
  if result is null then raise exception 'Unknown team code'; end if;
  return result;
end $$;

-- Adds a person to a team (doing it again is harmless).
create or replace function public.join_team(p_code text, p_name text)
returns void
language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from teams where code = upper(trim(p_code))) then
    raise exception 'Unknown team code';
  end if;
  insert into team_members (team_code, user_name) values (upper(trim(p_code)), trim(p_name))
  on conflict do nothing;
end $$;

-- Removes a person from a team. Their past entries stay but are no longer shown.
create or replace function public.leave_team(p_code text, p_name text)
returns void
language sql security definer set search_path = public as $$
  delete from team_members
  where team_code = upper(trim(p_code)) and lower(user_name) = lower(trim(p_name));
$$;

-- The members of a team, in the order they joined.
create or replace function public.team_members(p_code text)
returns table (user_name text, joined_at timestamptz)
language sql stable security definer set search_path = public as $$
  select m.user_name, m.joined_at
  from team_members m
  where m.team_code = upper(trim(p_code))
  order by m.joined_at;
$$;

-- All entries of a team, oldest first.
create or replace function public.team_entries(p_code text)
returns table (id uuid, user_name text, day date, count int, created_at timestamptz)
language sql stable security definer set search_path = public as $$
  select e.id, e.user_name, e.day, e.count, e.created_at
  from entries e
  where e.team_code = upper(trim(p_code))
  order by e.created_at;
$$;

-- Adds entries to a team. Entries whose id already exists are skipped, so a retry is harmless.
create or replace function public.add_entries(p_code text, p_rows json)
returns void
language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from teams where code = upper(trim(p_code))) then
    raise exception 'Unknown team code';
  end if;
  insert into entries (id, user_name, day, count, created_at, team_code)
  select r.id, r.user_name, r.day, r.count, coalesce(r.created_at, now()), upper(trim(p_code))
  from json_to_recordset(p_rows) as r (id uuid, user_name text, day date, count int, created_at timestamptz)
  on conflict (id) do nothing;
end $$;

-- Undo: removes a team's entries by id, only if they are less than a day old.
create or replace function public.remove_entries(p_code text, p_ids uuid[])
returns void
language sql security definer set search_path = public as $$
  delete from entries
  where team_code = upper(trim(p_code)) and id = any (p_ids) and created_at > now() - interval '1 day';
$$;

-- "Reset my progress" in the settings: deletes all of one person's entries in a team.
create or replace function public.reset_entries(p_code text, p_name text)
returns void
language sql security definer set search_path = public as $$
  delete from entries
  where team_code = upper(trim(p_code)) and lower(user_name) = lower(trim(p_name));
$$;

-- Saves (or moves) this phone's notification subscription to a team, with its language.
drop function if exists public.save_push_subscription(text, text, json);
create or replace function public.save_push_subscription(p_code text, p_name text, p_subscription json, p_lang text default 'en')
returns void
language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from teams where code = upper(trim(p_code))) then
    raise exception 'Unknown team code';
  end if;
  insert into push_subscriptions (endpoint, team_code, user_name, p256dh, auth, lang)
  values (p_subscription ->> 'endpoint', upper(trim(p_code)), trim(p_name),
          p_subscription -> 'keys' ->> 'p256dh', p_subscription -> 'keys' ->> 'auth',
          case when p_lang = 'fr' then 'fr' else 'en' end)
  on conflict (endpoint) do update
    set team_code = excluded.team_code, user_name = excluded.user_name,
        p256dh = excluded.p256dh, auth = excluded.auth, lang = excluded.lang;
end $$;

-- Stops notifications for this phone.
create or replace function public.delete_push_subscription(p_endpoint text)
returns void
language sql security definer set search_path = public as $$
  delete from push_subscriptions where endpoint = p_endpoint;
$$;

grant execute on function
  public.create_team(text),
  public.find_team(text),
  public.update_team_rules(text, int, int, date),
  public.team_entries(text),
  public.join_team(text, text),
  public.leave_team(text, text),
  public.team_members(text),
  public.add_entries(text, json),
  public.remove_entries(text, uuid[]),
  public.reset_entries(text, text),
  public.save_push_subscription(text, text, json, text),
  public.delete_push_subscription(text)
to anon, authenticated;
