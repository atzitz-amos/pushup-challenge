-- Shared table for the pushup challenge. Run this once in the Supabase SQL editor.
-- One row per saved session; everyone can read all rows so they see each other.

create table if not exists public.entries (
  id         uuid primary key,                 -- generated by the app, so retries never duplicate
  user_name  text not null check (char_length(user_name) between 1 and 20),
  day        date not null,
  count      int  not null check (count between 1 and 100),
  created_at timestamptz not null default now()
);

create index if not exists entries_day_idx on public.entries (day);

-- Row-level security: the app uses the public "anon" key, so these policies are
-- what limits it. Reading and adding are open; deleting is only allowed for rows
-- from the last day (that is what Undo needs), so old history can't be wiped.
alter table public.entries enable row level security;

drop policy if exists "Everyone can read" on public.entries;
create policy "Everyone can read" on public.entries
  for select to anon using (true);

drop policy if exists "Everyone can add" on public.entries;
create policy "Everyone can add" on public.entries
  for insert to anon with check (true);

drop policy if exists "Undo recent entries" on public.entries;
create policy "Undo recent entries" on public.entries
  for delete to anon using (created_at > now() - interval '1 day');
