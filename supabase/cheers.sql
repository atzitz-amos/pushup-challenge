-- Reactions and comments on someone's day ("cheers").
-- Only adds a table and functions: nothing that exists is changed, so running it
-- doesn't affect the app version people are using. Safe to run more than once.
-- (schema.sql contains the same block, for setting up a new project from scratch.)

create table if not exists public.cheers (
  id         uuid primary key,                       -- generated by the app, so retries never duplicate
  team_code  text not null references public.teams (code) on delete cascade,
  owner      text not null check (char_length(owner) between 1 and 20),  -- whose day it is
  day        date not null,
  author     text not null check (char_length(author) between 1 and 20),
  emoji      text check (char_length(emoji) between 1 and 16),           -- a reaction…
  body       text check (char_length(body) between 1 and 300),           -- …or a comment
  created_at timestamptz not null default now(),
  constraint cheers_one_kind check ((emoji is null) <> (body is null))
);
create index if not exists cheers_team_idx on public.cheers (team_code, day);
-- One reaction of each kind per person per day.
create unique index if not exists cheers_reaction_idx
  on public.cheers (team_code, lower(owner), day, lower(author), emoji) where emoji is not null;

alter table public.cheers enable row level security;
revoke all on table public.cheers from anon, authenticated;

-- All reactions and comments of a team, oldest first.
create or replace function public.team_cheers(p_code text)
returns table (id uuid, owner text, day date, author text, emoji text, body text, created_at timestamptz)
language sql stable security definer set search_path = public as $$
  select c.id, c.owner, c.day, c.author, c.emoji, c.body, c.created_at
  from cheers c
  where c.team_code = upper(trim(p_code))
  order by c.created_at;
$$;

-- Adds reactions and comments to a team. Rows whose id already exists (a retry), and
-- reactions someone already gave, are skipped.
create or replace function public.add_cheers(p_code text, p_rows json)
returns void
language plpgsql security definer set search_path = public as $$
begin
  if not exists (select 1 from teams where code = upper(trim(p_code))) then
    raise exception 'Unknown team code';
  end if;
  insert into cheers (id, team_code, owner, day, author, emoji, body, created_at)
  select r.id, upper(trim(p_code)), trim(r.owner), r.day, trim(r.author), r.emoji, nullif(trim(r.body), ''),
         least(coalesce(r.created_at, now()), now())
  from json_to_recordset(p_rows) as r (id uuid, owner text, day date, author text, emoji text, body text, created_at timestamptz)
  on conflict do nothing;
end $$;

-- Removes reactions and comments, only the ones the given person wrote.
create or replace function public.remove_cheers(p_code text, p_name text, p_ids uuid[])
returns void
language sql security definer set search_path = public as $$
  delete from cheers
  where team_code = upper(trim(p_code)) and lower(author) = lower(trim(p_name)) and id = any (p_ids);
$$;

-- "Reset my progress": deletes a person's messages and reactions, and the reactions on their days.
create or replace function public.reset_cheers(p_code text, p_name text)
returns void
language sql security definer set search_path = public as $$
  delete from cheers
  where team_code = upper(trim(p_code))
    and (lower(author) = lower(trim(p_name)) or lower(owner) = lower(trim(p_name)));
$$;

grant execute on function
  public.team_cheers(text),
  public.add_cheers(text, json),
  public.remove_cheers(text, text, uuid[]),
  public.reset_cheers(text, text)
to anon, authenticated;
