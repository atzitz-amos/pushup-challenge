function initialLang() {
  try {
    const saved = localStorage.getItem(KEY);
    if (saved in LANGS) return saved;
  } catch { /* storage unavailable */ }
  return (navigator.language || 'en').toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

let lang = initialLang();
document.documentElement.lang = lang;

export const getLang = () => lang;

export function setLang(next) {
  if (!(next in LANGS)) return;
  lang = next;
  document.documentElement.lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* ignore */ }
}

export function t(key, vars = {}) {
  const text = DICT[lang][key] ?? DICT.en[key] ?? key;
  return typeof text === 'function' ? text(vars) : text.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

// Dates in the current language (formatters are cached per language).
const formatters = new Map();
export function dateFmt(opts) {
  const k = lang + JSON.stringify(opts);
  if (!formatters.has(k)) formatters.set(k, new Intl.DateTimeFormat(lang, opts));
  return formatters.get(k);
}

export const num = (n) => Number(n).toLocaleString(lang);
export const capitalize = (text) => text.charAt(0).toUpperCase() + text.slice(1);

// Monday-first one-letter weekday names (L M M J V S D in French).
export function weekdayLetters() {
  // 1 January 2024 was a Monday.
  return Array.from({ length: 7 }, (_, i) => dateFmt({ weekday: 'narrow' }).format(new Date(2024, 0, 1 + i)).toUpperCase());
}

// Applies the static texts in the page: data-i18n (text), data-i18n-aria (aria-label),
// data-i18n-ph (placeholder). Templates are translated too, so pages built from them
// come out in the right language.
export function translatePage(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  for (const el of root.querySelectorAll('[data-i18n-ph]')) el.setAttribute('placeholder', t(el.dataset.i18nPh));
  for (const tpl of root.querySelectorAll('template')) translatePage(tpl.content);
  if (root === document) document.title = t('app.title');
}
